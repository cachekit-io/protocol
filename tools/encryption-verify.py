def frozen_order_failure(table: str, rows: object, frozen: tuple[str, ...]) -> str | None:
    """A FAIL line when `rows` do not open with the frozen rows in their frozen order, else None."""
    names = [row.get("name") if isinstance(row, dict) else None for row in rows] if isinstance(rows, list) else []
    if names[: len(frozen)] != list(frozen):
        return (
            f"FAIL frozen {table} rows missing or moved (append-only: never remove, rename or move a row): "
            f"want {list(frozen)} first, got {names[: len(frozen)]}"
        )
    return None


def hkdf_sha256(ikm: bytes, salt: bytes, info: bytes, length: int = 32) -> bytes:
    """RFC 5869 HKDF-Extract + Expand with SHA-256."""
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    okm, t, i = b"", b"", 1
    while len(okm) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        okm += t
        i += 1
    return okm[:length]


def construct_salt(domain: str, tenant_salt: str) -> bytes:
    d, t = domain.encode("utf-8"), tenant_salt.encode("utf-8")
    return b"cachekit_v1_" + bytes([len(d)]) + d + len(t).to_bytes(2, "big") + t


def derive_encryption_key(master_key: bytes, tenant_id: str) -> bytes:
    return hkdf_sha256(master_key, construct_salt("encryption", tenant_id), b"encryption")


def key_fingerprint(key: bytes) -> str:
    return hashlib.sha256(b"key_fingerprint_v1" + key).digest()[:16].hex()


def decrypt_with_keyring(keys: list[bytes], ciphertext: bytes, aad: bytes) -> tuple[int, bytes] | None:
    """Try each key once, in keyring order, with identical authenticated data."""
    from cryptography.exceptions import InvalidTag  # noqa: PLC0415
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM  # noqa: PLC0415

    nonce, sealed = ciphertext[:12], ciphertext[12:]
    for index, key in enumerate(keys):
        try:
            return index, AESGCM(key).decrypt(nonce, sealed, aad)
        except InvalidTag:
            continue
    return None


def aad_v3(tenant_id: str, cache_key: str, *, fmt: str, compressed: bool, original_type: str | None = None) -> bytes:
    """AAD v0x03 per spec/encryption.md — 4-byte BE length-prefixed components.

    Unlike interop-reference.py's aad_v3, this supports the optional fifth
    original_type component. The interop copy omits it DELIBERATELY — interop
    AAD is exactly four components; do not "harmonize" the two.
    """
    components = [
        tenant_id.encode("utf-8"),
        cache_key.encode("utf-8"),
        fmt.encode("utf-8"),
        TOKEN_TRUE if compressed else TOKEN_FALSE,
    ]
    if original_type is not None:
        components.append(original_type.encode("utf-8"))
    aad = bytearray([0x03])
    for component in components:
        aad += len(component).to_bytes(4, "big") + component
    return bytes(aad)


@functools.cache
def _load_tool(filename: str) -> ModuleType:
    """A sibling stdlib-only reference tool, loaded as a module (its filename is hyphenated)."""
    path = Path(__file__).resolve().parent / filename
    spec = importlib.util.spec_from_file_location(path.stem.replace("-", "_"), path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def one_document(data: bytes) -> bytes | None:
    """`data` if it is exactly one MessagePack document, else None: what a plain-MessagePack reader returns."""
    try:
        _load_tool("interop-reference.py").decode_value(data)
    except ValueError:
        return None
    return data


def envelope_value(data: bytes) -> bytes | None:
    """The bytes a ByteStorage envelope holds (LZ4-decompressed, checksum unchecked), or None if `data` is not one."""
    try:
        compressed, _, size, _, _ = _load_tool("wire-format-reference.py").decode_envelope(data)
        return _load_tool("interop-v2-reference.py").lz4_block_decompress(compressed, size)
    except ValueError:
        return None


def writer_shape_failure(vec: dict) -> str | None:
    """Why a WRITER_SHAPES vector no longer pins its writer's shape over that writer's container; None when it does."""
    fmt, compressed, original_type = WRITER_SHAPES[vec["name"]]
    if (vec["format"], vec["compressed"], vec.get("original_type")) != (fmt, compressed, original_type):
        return f"must keep the AAD shape ({fmt}, {compressed}, {original_type}) its writer emits"
    plaintext = bytes.fromhex(vec["plaintext_hex"])
    envelope = envelope_value(plaintext) is not None
    if compressed and not envelope:
        return "claims compressed True, but its plaintext is no ByteStorage envelope"
    if not compressed and (envelope or one_document(plaintext) is None):
        return "claims compressed False, but its plaintext is not one plain MessagePack document"
    return None


def verify_sealed_vector(
    label: str, vec: dict, tenant_id: str, keys: list[bytes], *, seal: bool, original_type: str | None = None
) -> tuple[bytes, int | None] | None:
    """Per-vector conformance body shared by every block: metadata, AAD rebuild, then decrypt + plaintext.

    Prints a FAIL line and returns None on the first mismatch. Otherwise returns the
    rebuilt AAD and the index of the key in `keys` that decrypted (None when `seal`
    is off). The caller prints the ok-line, so block-specific guards run first.
    """
    if not isinstance(vec["compressed"], bool) or vec["format"] not in FORMAT_REGISTRY:
        print(f"FAIL {label}: invalid metadata (compressed must be a JSON boolean, format must be in {sorted(FORMAT_REGISTRY)})")
        return None
    aad = aad_v3(tenant_id, vec["cache_key"], fmt=vec["format"], compressed=vec["compressed"], original_type=original_type)
    if aad.hex() != vec["aad_hex"]:
        print(f"FAIL {label}: AAD mismatch\n  expected {vec['aad_hex']}\n  rebuilt  {aad.hex()}")
        return None
    if not seal:
        return aad, None
    result = decrypt_with_keyring(keys, bytes.fromhex(vec["ciphertext_hex"]), aad)
    if result is None:
        print(f"FAIL {label}: decrypt failed (InvalidTag — AAD/key/ciphertext mismatch)")
        return None
    index, plaintext = result
    if plaintext.hex() != vec["plaintext_hex"]:
        print(f"FAIL {label}: plaintext mismatch\n  expected {vec['plaintext_hex']}\n  got      {plaintext.hex()}")
        return None
    return aad, index


def verify_aad_rejects(doc: dict, key: bytes, *, seal: bool) -> int:
    """Return the number of failed AAD reject rows (spec/encryption.md ENC-1: readers never retry with another AAD input).

    Each row names the vector in `vectors` whose ciphertext it carries (`sealed_as`) and presents AAD inputs that differ
    from that vector's in exactly one of cache_key, format, compressed and original_type (present or absent). Its
    aad_hex must rebuild from what it presents. With `cryptography`, the ciphertext must fail authentication under the
    presented AAD, which the one-input rule already implies; the check shows the row's claim with the cipher itself.
    """
    rows = doc.get("aad_reject_vectors")
    if not isinstance(rows, list) or not all(isinstance(row, dict) and isinstance(row.get("name"), str) for row in rows):
        print("FAIL aad_reject_vectors missing, or a row that is not an object with a string name")
        return 1
    failures = 0
    missing = set(FROZEN_AAD_REJECT_VECTORS) - {row["name"] for row in rows}
    if missing:
        print(f"FAIL frozen aad_reject_vectors missing (append-only, never rename): {sorted(missing)}")
        failures += 1
    if moved := frozen_order_failure("aad_reject_vectors", rows, tuple(FROZEN_AAD_REJECT_VECTORS)):
        print(moved)
        failures += 1
    sealed = {v["name"]: v for v in doc["vectors"]}
    seen: set[str] = set()
    checked: dict[str, tuple[dict, dict]] = {}
    for row in rows:
        name = row["name"]
        label = f"aad_reject {name}"
        if set(row) - {"original_type"} != AAD_REJECT_FIELDS:
            print(f"FAIL {label}: fields {sorted(row)} != {sorted(AAD_REJECT_FIELDS)} (original_type optional)")
            failures += 1
            continue
        if name in seen:
            print(f"FAIL {label}: duplicate name")
            failures += 1
            continue
        seen.add(name)
        if not isinstance(row["note"], str) or not row["note"].strip():
            print(f"FAIL {label}: note must be a non-empty string")
            failures += 1
            continue
        if not isinstance(row["compressed"], bool) or row["format"] not in FORMAT_REGISTRY:
            print(f"FAIL {label}: invalid metadata (compressed must be a JSON boolean, format must be in {sorted(FORMAT_REGISTRY)})")
            failures += 1
            continue
        base = sealed.get(row["sealed_as"])
        if base is None:
            print(f"FAIL {label}: sealed_as names no vector in `vectors`: {row['sealed_as']!r}")
            failures += 1
            continue
        if row["ciphertext_hex"] != base["ciphertext_hex"]:
            print(f"FAIL {label}: ciphertext is not {row['sealed_as']}'s")
            failures += 1
            continue
        aad = aad_v3(doc["tenant_id"], row["cache_key"], fmt=row["format"], compressed=row["compressed"], original_type=row.get("original_type"))
        if aad.hex() != row["aad_hex"]:
            print(f"FAIL {label}: AAD mismatch\n  expected {row['aad_hex']}\n  rebuilt  {aad.hex()}")
            failures += 1
            continue
        differs = [f for f in AAD_INPUTS if (f in row) != (f in base) or row.get(f) != base.get(f)]
        if len(differs) != 1:
            print(f"FAIL {label}: differs from {row['sealed_as']} in {differs or 'no'} AAD input(s); a row presents exactly one alternative")
            failures += 1
            continue
        sealed_as, component, presented, container, retry_value = FROZEN_AAD_REJECT_VECTORS.get(
            name, (row["sealed_as"], differs[0], row.get(differs[0]), None, None)
        )
        if row["sealed_as"] != sealed_as or differs != [component] or row.get(component) != presented:
            print(f"FAIL {label}: must carry {sealed_as}'s ciphertext and present {component} {presented!r}, as its frozen name declares")
            failures += 1
            continue
        if container is not None and (CONFORMING_READERS[container](bytes.fromhex(base["plaintext_hex"])) is not None) != retry_value:
            print(
                f"FAIL {label}: a {container} reader that retried {'would not' if retry_value else 'would'} read a value from "
                f"{sealed_as}'s plaintext, against what its frozen name declares"
            )
            failures += 1
            continue
        if seal and decrypt_with_keyring([key], bytes.fromhex(row["ciphertext_hex"]), aad) is not None:
            print(f"FAIL {label}: decrypts under the AAD it presents, so a reader that never retries returns a value")
            failures += 1
            continue
        checked[name] = (row, base)
        print(f"ok  {label} ({differs[0]} differs{'; authentication fails' if seal else ''})")
    # Each retrying reader must rebuild the sealed vector's AAD from what a row it lists presents: that AAD
    # authenticates the ciphertext (the sealed vector's own check), so the retry decrypts the row.
    listed: set[str] = set()
    for label, (retries, targets) in WRONG_AAD_RETRIES.items():
        for target in targets:
            listed.add(target)
            if target not in FROZEN_AAD_REJECT_VECTORS:
                print(f"FAIL wrong AAD retry {label!r} lists {target}, which is not a frozen row of its table")
                failures += 1
                continue
            if target not in checked:
                continue  # the frozen-name or row guards report it
            row, base = checked[target]
            presented = {f: row[f] for f in AAD_INPUTS if f in row}
            rebuilt = {
                aad_v3(doc["tenant_id"], i["cache_key"], fmt=i["format"], compressed=i["compressed"], original_type=i.get("original_type")).hex()
                for i in retries(presented)
            }
            if base["aad_hex"] not in rebuilt:
                print(f"FAIL wrong AAD retry {label!r} never reaches {target}'s sealed AAD, so the row no longer shows the mistake its note names")
                failures += 1
    unshown = sorted((set(FROZEN_AAD_REJECT_VECTORS) | set(checked)) - listed)
    if unshown:
        print(f"FAIL no wrong AAD retry shows why these rows exist: {unshown}")
        failures += 1
    return failures


