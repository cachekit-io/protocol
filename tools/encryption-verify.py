def verdict(key: bytes | None) -> str | None:
    """What an entry point's answer pins: None for a refusal, else the fingerprint of the key it derives for "default"."""
    return None if key is None else key_fingerprint(derive_encryption_key(key, DEFAULT_TENANT_ID))


def verify_wrong_entry_points(rows: dict[str, tuple[str, dict]]) -> int:
    """Return the number of wrong entry points that judge a row they list correctly (or name a row of the wrong kind).

    A raw-bytes entry point may list an accept row, which it is fed as decoded bytes. A missing row is skipped: the
    frozen-name guard reports it.
    """
    failures = 0
    accept_rows = set(FROZEN_MASTER_KEY_INPUT_VECTORS["accept_vectors"])
    raw_rows = set(FROZEN_MASTER_KEY_INPUT_VECTORS["raw_reject_vectors"])
    hex_rows = accept_rows | set(FROZEN_MASTER_KEY_INPUT_VECTORS["reject_vectors"])
    listed: set[str] = set()
    for entry_points, kind in ((WRONG_HEX_ENTRY_POINTS, hex_rows), (WRONG_RAW_ENTRY_POINTS, raw_rows | accept_rows)):
        for label, (entry_point, targets) in entry_points.items():
            for target in targets:
                listed.add(target)
                if target not in kind:
                    print(f"FAIL wrong entry point {label!r} lists {target}, which is not a frozen row of its kind")
                    failures += 1
                    continue
                if target not in rows:
                    continue
                table, row = rows[target]
                try:
                    if table == "raw_reject_vectors":
                        given: str | bytes = bytes.fromhex(row["raw_key_hex"])
                    elif entry_points is WRONG_RAW_ENTRY_POINTS:
                        given = bytes.fromhex(row["master_key_hex"])
                    else:
                        given = row["master_key_hex"]
                    got = verdict(entry_point(given))
                except (ValueError, OverflowError) as exc:
                    print(f"FAIL wrong entry point {label!r} raised on {target}: {exc}")
                    failures += 1
                    continue
                if got == row.get("derived_key_fingerprint_hex"):
                    print(
                        f"FAIL wrong entry point {label!r} judges {target} correctly, so the row no longer shows the "
                        "mistake its note names"
                    )
                    failures += 1
    # A row a later version adds needs a wrong entry point too, or its note's claims go unchecked.
    unshown = sorted((hex_rows | raw_rows | set(rows)) - listed)
    if unshown:
        print(f"FAIL no wrong entry point shows why these rows exist: {unshown}")
        failures += 1
    return failures


# Keyring configurations (spec/encryption.md § Key Rotation (Keyring), ENC-7 and ENC-9): a current master key and the
# decrypt-only keys a keyring is loaded from, and whether a conforming SDK accepts it at load. Names are frozen and a row
# has exactly these fields.
FROZEN_KEYRING_CONFIGURATIONS = {
    "keyring_three_decrypt_only_keys": "accept",
    "keyring_four_decrypt_only_keys": "reject",
    "keyring_current_key_decrypt_only": "reject",
    "keyring_current_key_decrypt_only_uppercase": "reject",
}
KEYRING_CONFIGURATION_FIELDS = frozenset({"name", "current_master_key_hex", "decrypt_only_master_keys_hex", "verdict", "note"})
DECRYPT_ONLY_CAP = 3


def keyring_loads(current: str, decrypt_only: list[str], *, lenient: bool, cap: int = DECRYPT_ONLY_CAP, compare: bool = True) -> bool:
    """Whether an SDK accepts the configuration at load, under one reading of rule 1 (`read_hex_key`).

    A conforming SDK refuses a key it cannot read, more than `cap` decrypt-only keys, and the current key among the
    decrypt-only keys, compared as key bytes. `cap` and `compare` let a wrong entry point loosen one of those rules.
    """
    keys = [read_hex_key(text, lenient=lenient) for text in (current, *decrypt_only)]
    if any(key is None or len(key) != KEY_BYTES for key in keys):
        return False
    return len(decrypt_only) <= cap and not (compare and keys[0] in keys[1:])


# Plausible wrong keyring loaders, one per mistake a configuration note names: each returns whether it accepts the
# configuration at load and must misjudge every row it lists; it lists a row only if that row's note names its mistake.
# Each reads uppercase hex as lowercase, the reading under which every mistake shows.
WRONG_KEYRING_LOADS: dict[str, tuple[Callable[[str, list[str]], bool], tuple[str, ...]]] = {
    "no cap on decrypt-only keys": (
        lambda c, d: keyring_loads(c, d, lenient=True, cap=len(d)),
        ("keyring_four_decrypt_only_keys",),
    ),
    "the first three decrypt-only keys kept and the rest dropped": (
        lambda c, d: keyring_loads(c, d[:DECRYPT_ONLY_CAP], lenient=True),
        ("keyring_four_decrypt_only_keys",),
    ),
    "a cap of two decrypt-only keys": (
        lambda c, d: keyring_loads(c, d, lenient=True, cap=DECRYPT_ONLY_CAP - 1),
        ("keyring_three_decrypt_only_keys",),
    ),
    "no check that the current key is not a decrypt-only key": (
        lambda c, d: keyring_loads(c, d, lenient=True, compare=False),
        ("keyring_current_key_decrypt_only", "keyring_current_key_decrypt_only_uppercase"),
    ),
    "the current key compared with each decrypt-only key as a string": (
        lambda c, d: keyring_loads(c, d, lenient=True, compare=False) and c not in d,
        ("keyring_current_key_decrypt_only_uppercase",),
    ),
    "the current key compared with the first decrypt-only key only": (
        lambda c, d: keyring_loads(c, d, lenient=True, compare=False) and keyring_loads(c, d[:1], lenient=True),
        ("keyring_current_key_decrypt_only",),
    ),
    "the current key compared with the last decrypt-only key only": (
        lambda c, d: keyring_loads(c, d, lenient=True, compare=False) and keyring_loads(c, d[-1:], lenient=True),
        ("keyring_current_key_decrypt_only",),
    ),
}


def verify_keyring_configurations(keyring: dict | None) -> int:
    """Return the number of failed keyring configuration checks (spec/encryption.md ENC-7 and ENC-9).

    Each row's keys must each be a valid 32-byte key once uppercase is read as lowercase, with no key twice in the
    decrypt-only list, and only a repeat of the current key in another case may hold uppercase, so a row decides only
    the keyring rule it targets. Its verdict must be what a conforming load gives under each reading of rule 1, so no
    row settles uppercase handling; then each wrong loader must misjudge the rows it lists.
    """
    block = keyring.get("configuration") if isinstance(keyring, dict) else None
    vectors = block.get("vectors") if isinstance(block, dict) else None
    if not isinstance(vectors, list) or not all(isinstance(row, dict) and isinstance(row.get("name"), str) for row in vectors):
        print("FAIL keyring configuration rows missing, or a row that is not an object with a string name")
        return 1
    failures = 0
    if not isinstance(block.get("note"), str) or not block["note"].strip():
        print("FAIL keyring configuration: note must be a non-empty string")
        failures += 1
    missing = set(FROZEN_KEYRING_CONFIGURATIONS) - {row["name"] for row in vectors}
    if missing:
        print(f"FAIL frozen keyring configuration rows missing (append-only, never rename): {sorted(missing)}")
        failures += 1
    if moved := frozen_order_failure("keyring.configuration.vectors", vectors, tuple(FROZEN_KEYRING_CONFIGURATIONS)):
        print(moved)
        failures += 1
    rows: dict[str, dict] = {}
    for row in vectors:
        name = row.get("name")
        label = f"keyring configuration {name}"
        if set(row) != KEYRING_CONFIGURATION_FIELDS:
            print(f"FAIL {label}: fields {sorted(row)} != {sorted(KEYRING_CONFIGURATION_FIELDS)}")
            failures += 1
            continue
        if name in rows:
            print(f"FAIL {label}: duplicate name")
            failures += 1
            continue
        current, decrypt_only = row["current_master_key_hex"], row["decrypt_only_master_keys_hex"]
        if not (
            isinstance(row["note"], str) and row["note"].strip() and isinstance(current, str) and isinstance(decrypt_only, list)
            and all(isinstance(k, str) and set(k) <= ROW_CHARACTERS for k in decrypt_only) and set(current) <= ROW_CHARACTERS
        ):
            print(f"FAIL {label}: needs a non-empty note, a key string and a list of key strings of printable ASCII")
            failures += 1
            continue
        if row["verdict"] != FROZEN_KEYRING_CONFIGURATIONS.get(name, row["verdict"]) or row["verdict"] not in ("accept", "reject"):
            print(f"FAIL {label}: verdict must be accept or reject, and the one its frozen name declares")
            failures += 1
            continue
        read = [read_hex_key(text, lenient=True) for text in (current, *decrypt_only)]
        if any(key is None or len(key) != KEY_BYTES for key in read):
            print(f"FAIL {label}: every key must be a valid {KEY_BYTES}-byte key once uppercase is read, so only the keyring rules decide the row")
            failures += 1
            continue
        if any(read_hex_key(text) is None and (text == current or text.lower() != current) for text in (current, *decrypt_only)):
            print(f"FAIL {label}: only a repeat of the current key in another case may need the lenient reading of rule 1")
            failures += 1
            continue
        if len(set(read[1:])) != len(read) - 1:
            print(f"FAIL {label}: a key appears twice in the decrypt-only list, which the spec leaves open")
            failures += 1
            continue
        rows[name] = row
        wrong = [r for r, lenient in READINGS.items() if ("accept" if keyring_loads(current, decrypt_only, lenient=lenient) else "reject") != row["verdict"]]
        if wrong:
            print(f"FAIL {label}: a conforming load that {wrong[0]} does not {row['verdict']} it")
            failures += 1
            continue
        print(f"ok  {label} ({row['verdict']})")
    listed: set[str] = set()
    for label, (loads, targets) in WRONG_KEYRING_LOADS.items():
        for target in targets:
            listed.add(target)
            if target not in FROZEN_KEYRING_CONFIGURATIONS:
                print(f"FAIL wrong keyring loader {label!r} lists {target}, which is not a frozen row of its table")
                failures += 1
                continue
            row = rows.get(target)
            if row is None:
                continue  # the frozen-name or row guards report it
            if ("accept" if loads(row["current_master_key_hex"], row["decrypt_only_master_keys_hex"]) else "reject") == row["verdict"]:
                print(f"FAIL wrong keyring loader {label!r} judges {target} correctly, so the row no longer shows the mistake its note names")
                failures += 1
    unshown = sorted((set(FROZEN_KEYRING_CONFIGURATIONS) | set(rows)) - listed)
    if unshown:
        print(f"FAIL no wrong keyring loader shows why these rows exist: {unshown}")
        failures += 1
    return failures


def verify_master_key_input(block: dict | None, default_tenant: dict | None, main_master_key_hex: str, *, seal: bool) -> int:
    """Return the number of failed master key input checks (spec/intent-presets.md § Master Key Input).

    Accept rows must be accepted, and reject rows refused, under every conformant length rule and both readings of
    what rule 1 leaves open; raw reject rows must not be 32 bytes. An accept row shares neither its master key nor
    its cache_key or plaintext with a default_tenant entry or another accept row, so a test can read them under
    different keys (PRE-51). Each accept row's fingerprint, AAD and (with `cryptography`) seal are checked under the
    key its own master key derives, then each wrong entry point must misjudge the rows it lists.
    """
    if block is None:
        print("FAIL master_key_input rows missing")
        return 1
    if block.get("tenant_id") != DEFAULT_TENANT_ID:
        print(f"FAIL master_key_input: tenant_id must be the literal {DEFAULT_TENANT_ID!r}; got {block.get('tenant_id')!r}")
        return 1
    failures = 0
    # A row joins `rows`, and so the wrong-entry-point check, once its fields, name, note and characters pass, so a row
    # whose verdict is wrong is still checked against the models. A model that cannot parse such a row (an odd-length
    # accept row, say) raises, and verify_wrong_entry_points reports that as a failure, not a traceback.
    dt_vectors = (default_tenant or {}).get("vectors", [])
    accept_vectors = block.get("accept_vectors", [])
    rows: dict[str, tuple[str, dict]] = {}
    seen: set[str] = set()
    for table, frozen in FROZEN_MASTER_KEY_INPUT_VECTORS.items():
        if moved := frozen_order_failure(f"master_key_input.{table}", block.get(table, []), frozen):
            print(moved)
            failures += 1
        for row in block.get(table, []):
            name = row.get("name")
            label = f"master_key_input {name}"
            if set(row) != MASTER_KEY_INPUT_FIELDS[table]:
                print(f"FAIL {label}: fields {sorted(row)} != {sorted(MASTER_KEY_INPUT_FIELDS[table])}")
                failures += 1
                continue
            if name in seen:
                print(f"FAIL {label}: duplicate name")
                failures += 1
                continue
            seen.add(name)
            if not isinstance(row["note"], str) or not row["note"].strip():
                print(f"FAIL {label}: note must be a non-empty string")
                failures += 1
                continue
            if table == "raw_reject_vectors":
                raw_hex = row["raw_key_hex"]
                if len(raw_hex) % 2 or not set(raw_hex) <= LOWER_HEX:
                    print(f"FAIL {label}: raw_key_hex must be lowercase hex")
                    failures += 1
                    continue
                rows[name] = (table, row)
                if len(bytes.fromhex(raw_hex)) == KEY_BYTES:
                    print(f"FAIL {label}: a raw-bytes entry point takes exactly {KEY_BYTES} bytes, so this row is no reject")
                    failures += 1
                else:
                    print(f"ok  {label}")
                continue
            text = row["master_key_hex"]
            if not set(text) <= ROW_CHARACTERS:
                print(f"FAIL {label}: holds a character other than printable ASCII and ASCII white space")
                failures += 1
                continue
            rows[name] = (table, row)
            wanted = table == "accept_vectors"
            others = [v for v in accept_vectors if v is not row]
            if wanted and (
                text in [main_master_key_hex, *(v.get("master_key_hex") for v in others)]
                or any(
                    row["cache_key"] == v.get("cache_key") or row["plaintext_hex"] == v.get("plaintext_hex")
                    for v in dt_vectors + others
                )
            ):
                print(
                    f"FAIL {label}: shares its master key, cache_key or plaintext with a default_tenant entry or another "
                    "accept row, so a test cannot read them under different keys"
                )
                failures += 1
                continue
            wrong = [
                f"an entry point that takes {rule} and {reading}"
                for reading, lenient in READINGS.items()
                for rule, accepts in HEX_LENGTH_RULES.items()
                if ((key := read_hex_key(text, lenient=lenient)) is not None and accepts(len(key))) != wanted
            ]
            if wrong:
                print(f"FAIL {label}: {wrong[0]} {'refuses' if wanted else 'accepts'} it, so the row decides what the spec leaves open")
                failures += 1
                continue
            if not wanted:
                print(f"ok  {label}")
                continue
            derived = derive_encryption_key(bytes.fromhex(text), block["tenant_id"])
            if key_fingerprint(derived) != row["derived_key_fingerprint_hex"]:
                print(f"FAIL {label}: derived-key fingerprint mismatch (derived {key_fingerprint(derived)})")
                failures += 1
                continue
            if verify_sealed_vector(label, row, block["tenant_id"], [derived], seal=seal) is None:
                failures += 1
                continue
            print(f"ok  {label}" if seal else f"ok  {label} (AAD + fingerprint only)")
    return failures + verify_wrong_entry_points(rows)


def verify(doc: dict, *, require_seal: bool) -> int:
    failures = 0

    unknown = sorted(set(vector_tables(doc)) - VECTOR_TABLES)
    if unknown:
        print(f"FAIL unknown vector table(s) {unknown}: tools/conformance.py would index rows this verifier skips")
        return 1

    missing = set(FROZEN_VECTOR_NAMES) - {v["name"] for v in doc["vectors"]}
    if missing:
        print(f"FAIL frozen vectors missing (append-only file — never remove/rename): {sorted(missing)}")
        return 1
    if moved := frozen_order_failure("vectors", doc["vectors"], FROZEN_VECTOR_NAMES):
        print(moved)
        failures += 1

    key = derive_encryption_key(bytes.fromhex(doc["master_key_hex"]), doc["tenant_id"])
    if key_fingerprint(key) != doc["derived_key_fingerprint_hex"]:
        print(f"FAIL key fingerprint: derived {key_fingerprint(key)}, pinned {doc['derived_key_fingerprint_hex']}")
        return 1
    print(f"ok  key fingerprint {doc['derived_key_fingerprint_hex']}")

    try:
        # Probe only: decrypt_with_keyring imports these again where it uses them.
        from cryptography.exceptions import InvalidTag  # noqa: F401, PLC0415
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM  # noqa: F401, PLC0415

        seal = True
    except ImportError:
        if require_seal:
            print("FAIL --require-seal set but `cryptography` is not installed")
            return 1
        seal = False
        print("note: `cryptography` not installed — AAD reconstruction only, AES-GCM seal NOT verified")

    for vec in doc["vectors"]:
        name = vec["name"]
        if verify_sealed_vector(name, vec, doc["tenant_id"], [key], seal=seal, original_type=vec.get("original_type")) is None:
            failures += 1
            continue
        if name in WRITER_SHAPES and (why := writer_shape_failure(vec)):
            print(f"FAIL {name}: {why}")
            failures += 1
            continue
        print(f"ok  {name}")

    failures += verify_aad_rejects(doc, key, seal=seal)
    failures += verify_decrypted_containers(doc, key, seal=seal)
    failures += verify_keyring(doc.get("keyring"), seal=seal)
    failures += verify_keyring_configurations(doc.get("keyring"))
    failures += verify_default_tenant(doc.get("default_tenant"), bytes.fromhex(doc["master_key_hex"]), seal=seal)
    failures += verify_master_key_input(doc.get("master_key_input"), doc.get("default_tenant"), doc["master_key_hex"], seal=seal)

    if failures:
        print(f"{failures} vector(s) FAILED")
        return 1
    mode = "AAD + AES-GCM seal" if seal else "AAD-only"
    keyring_count = len(doc.get("keyring", {}).get("vectors", []))
    default_count = len(doc.get("default_tenant", {}).get("vectors", []))
    master_key_count = sum(len(doc["master_key_input"][table]) for table in FROZEN_MASTER_KEY_INPUT_VECTORS)
    print(
        f"all {len(doc['vectors'])} encryption vectors plus {len(doc['aad_reject_vectors'])} AAD reject, "
        f"{len(doc['decrypted_container']['vectors'])} post-decryption container, {keyring_count} "
        f"keyring, {len(doc['keyring']['configuration']['vectors'])} keyring configuration, {default_count} default-tenant "
        f"and {master_key_count} master key input vectors verified ({mode})"
    )
    return 0


def main() -> int:
    require_seal = "--require-seal" in sys.argv[1:]
    return verify(json.loads(VECTORS_PATH.read_text()), require_seal=require_seal)


if __name__ == "__main__":
    sys.exit(main())
