def verify_decrypted_containers(doc: dict, key: bytes, *, seal: bool) -> int:
    """Return the number of failed post-decryption container checks (spec/encryption.md ENC-2 and ENC-3).

    Each row must be sealed under its reader's AAD (rebuilt, and with `cryptography` decrypted), hold the plaintext its
    name pins, and a conforming reader of that container must give what `outcome` says: `error`, nothing, or
    `not_unwrapped`, anything but the value inside the plaintext's envelope (the plaintext as one MessagePack document,
    or nothing). Then each wrong reader must return a value its row's outcome forbids.
    """
    block = doc.get("decrypted_container")
    vectors = block.get("vectors") if isinstance(block, dict) else None
    if not isinstance(vectors, list) or not all(isinstance(row, dict) and isinstance(row.get("name"), str) for row in vectors):
        print("FAIL decrypted_container rows missing, or a row that is not an object with a string name")
        return 1
    failures = 0
    if not isinstance(block.get("note"), str) or not block["note"].strip():
        print("FAIL decrypted_container: note must be a non-empty string")
        failures += 1
    missing = set(FROZEN_CONTAINER_VECTORS) - {row.get("name") for row in block["vectors"]}
    if missing:
        print(f"FAIL frozen decrypted_container rows missing (append-only, never rename): {sorted(missing)}")
        failures += 1
    if moved := frozen_order_failure("decrypted_container.vectors", vectors, tuple(FROZEN_CONTAINER_VECTORS)):
        print(moved)
        failures += 1
    interop_keys = {v.get("expected_key") for v in json.loads(INTEROP_VECTORS_PATH.read_text()).get("key_vectors", [])}
    rows: dict[str, dict] = {}
    for row in block["vectors"]:
        name = row.get("name")
        label = f"decrypted_container {name}"
        if set(row) - {"original_type"} != CONTAINER_FIELDS:
            print(f"FAIL {label}: fields {sorted(row)} != {sorted(CONTAINER_FIELDS)} (original_type optional)")
            failures += 1
            continue
        if name in rows:
            print(f"FAIL {label}: duplicate name")
            failures += 1
            continue
        if not isinstance(row["note"], str) or not row["note"].strip():
            print(f"FAIL {label}: note must be a non-empty string")
            failures += 1
            continue
        reader, outcome, pin = FROZEN_CONTAINER_VECTORS.get(name, (row["reader"], row["outcome"], None))
        if (row["reader"], row["outcome"]) != (reader, outcome) or reader not in READER_AAD or outcome not in CONTAINER_OUTCOMES:
            print(f"FAIL {label}: reader must be one of {sorted(READER_AAD)}, outcome one of {list(CONTAINER_OUTCOMES)}, as its frozen name declares")
            failures += 1
            continue
        fmt, compressed, original_type = READER_AAD[reader]
        if (row["format"], row["compressed"], row.get("original_type")) != (fmt, compressed, original_type):
            print(f"FAIL {label}: the {reader} reader builds its AAD with format {fmt}, compressed {compressed} and original_type {original_type}")
            failures += 1
            continue
        if reader == "interop" and row["cache_key"] not in interop_keys:
            print(f"FAIL {label}: an interop row's cache_key must be one of interop-mode.json's keys, so a test can read it as an interop operation")
            failures += 1
            continue
        if verify_sealed_vector(label, row, doc["tenant_id"], [key], seal=seal, original_type=row.get("original_type")) is None:
            failures += 1
            continue
        plaintext = bytes.fromhex(row["plaintext_hex"])
        got = CONFORMING_READERS[reader](plaintext)
        inner = envelope_value(plaintext)
        if outcome == "not_unwrapped" and (inner is None or got == inner):
            print(f"FAIL {label}: holds no envelope whose value a conforming reader declines, so not_unwrapped pins nothing")
            failures += 1
            continue
        if outcome == "error" and got is not None:
            print(f"FAIL {label}: a conforming {reader} reader returns a value from it")
            failures += 1
            continue
        rows[name] = row
        # Checked last, and without dropping the row, so the wrong readers still run on an edited plaintext.
        if pin is not None and hashlib.sha256(plaintext).hexdigest() != pin:
            print(f"FAIL {label}: plaintext differs from the bytes its frozen name pins")
            failures += 1
            continue
        print(f"ok  {label} ({row['reader']}: {row['outcome']})")
    listed: set[str] = set()
    for label, (read, targets) in WRONG_CONTAINER_READERS.items():
        for target in targets:
            listed.add(target)
            if target not in FROZEN_CONTAINER_VECTORS:
                print(f"FAIL wrong container reader {label!r} lists {target}, which is not a frozen row of its table")
                failures += 1
                continue
            row = rows.get(target)
            if row is None:
                continue  # the frozen-name or row guards report it
            plaintext = bytes.fromhex(row["plaintext_hex"])
            got = read(plaintext)
            forbidden = got == envelope_value(plaintext) if row["outcome"] == "not_unwrapped" else got is not None
            if not forbidden:
                print(f"FAIL wrong container reader {label!r} returns what {target}'s outcome allows, so the row no longer shows the mistake its note names")
                failures += 1
    unshown = sorted((set(FROZEN_CONTAINER_VECTORS) | set(rows)) - listed)
    if unshown:
        print(f"FAIL no wrong container reader shows why these rows exist: {unshown}")
        failures += 1
    return failures


def verify_keyring(keyring: dict | None, *, seal: bool) -> int:
    """Return the number of failed keyring checks (spec/encryption.md § Key Rotation).

    Entry derivation, metadata, AAD reconstruction and fingerprint selection are
    stdlib and always run; only the decrypt attempts need `cryptography` (`seal`).
    """
    if keyring is None:
        print("FAIL keyring vectors missing")
        return 1
    failures = 0

    entries = keyring.get("entries", [])
    ids = [entry.get("id") for entry in entries]
    if len(set(ids)) != len(ids) or not set(KEYRING_ORDER) <= set(ids):
        print(f"FAIL keyring entries must have unique ids including {sorted(KEYRING_ORDER)}; got {ids}")
        return failures + 1
    derived_keys: dict[str, bytes] = {}
    for entry in entries:
        derived = derive_encryption_key(bytes.fromhex(entry["master_key_hex"]), keyring["tenant_id"])
        derived_keys[entry["id"]] = derived
        if key_fingerprint(derived) != entry["derived_key_fingerprint_hex"]:
            print(f"FAIL keyring {entry['id']}: derived-key fingerprint mismatch")
            failures += 1
    # Selection table for the per-entry-identity path: fingerprints of the
    # HKDF-DERIVED per-tenant encryption keys only — a master-key fingerprint
    # is deliberately not in here, so a vector carrying one cannot select.
    derived_fingerprints = {key_fingerprint(derived): key_id for key_id, derived in derived_keys.items()}

    vectors = keyring.get("vectors", [])
    if moved := frozen_order_failure("keyring.vectors", vectors, tuple(FROZEN_KEYRING_VECTORS)):
        print(moved)
        failures += 1
    if not seal:
        print("note: keyring decrypt checks require cryptography — AAD, metadata and fingerprint selection only")

    full_keyring = [derived_keys[key_id] for key_id in KEYRING_ORDER]
    current_only = [derived_keys[KEYRING_ORDER[0]]]
    for vec in vectors:
        name = vec["name"]
        encrypted_with = vec.get("encrypted_with")
        if encrypted_with not in KEYRING_ORDER or FROZEN_KEYRING_VECTORS.get(name, encrypted_with) != encrypted_with:
            print(
                f"FAIL keyring {name}: encrypted_with must be the entry the frozen name declares (one of {list(KEYRING_ORDER)}); got {encrypted_with!r}"
            )
            failures += 1
            continue
        if derived_fingerprints.get(vec.get("key_fingerprint_hex")) != encrypted_with:
            print(
                f"FAIL keyring {name}: stored key fingerprint must select the HKDF-derived key of {encrypted_with} (never a master key)"
            )
            failures += 1
            continue
        checked = verify_sealed_vector(f"keyring {name}", vec, keyring["tenant_id"], full_keyring, seal=seal)
        if checked is None:
            failures += 1
            continue
        if not seal:
            print(f"ok  keyring {name} (AAD + fingerprint selection only)")
            continue

        aad, index = checked
        if index != KEYRING_ORDER.index(encrypted_with):
            print(f"FAIL keyring {name}: decrypted with keyring entry {KEYRING_ORDER[index]}, expected {encrypted_with}")
            failures += 1
            continue
        ciphertext = bytes.fromhex(vec["ciphertext_hex"])
        if encrypted_with != KEYRING_ORDER[0] and decrypt_with_keyring(current_only, ciphertext, aad) is not None:
            print(f"FAIL keyring {name}: [{KEYRING_ORDER[0]}] alone accepted the {encrypted_with} entry")
            failures += 1
            continue
        print(f"ok  keyring {name}")
    return failures


def verify_default_tenant(block: dict | None, master_key: bytes, *, seal: bool) -> int:
    """Return the number of failed default-tenant checks (intent-presets.md rule 5).

    The block pins tenant "default" under the main master key: fingerprint of the
    HKDF-derived key, AAD reconstruction with "default" as component 1, and (with
    `cryptography`) the seal. An SDK that decrypts these through its preset with NO
    tenant configured has demonstrated the cross-SDK default.
    """
    if block is None:
        print("FAIL default_tenant vectors missing")
        return 1
    failures = 0
    if block.get("tenant_id") != DEFAULT_TENANT_ID:
        print(f"FAIL default_tenant: tenant_id must be the literal {DEFAULT_TENANT_ID!r}; got {block.get('tenant_id')!r}")
        return 1
    key = derive_encryption_key(master_key, DEFAULT_TENANT_ID)
    if key_fingerprint(key) != block.get("derived_key_fingerprint_hex"):
        print(f"FAIL default_tenant: derived-key fingerprint mismatch (derived {key_fingerprint(key)})")
        return 1
    vectors = block.get("vectors", [])
    if moved := frozen_order_failure("default_tenant.vectors", vectors, FROZEN_DEFAULT_TENANT_VECTOR_NAMES):
        print(moved)
        failures += 1
    for vec in vectors:
        name = vec["name"]
        if verify_sealed_vector(f"default_tenant {name}", vec, DEFAULT_TENANT_ID, [key], seal=seal) is None:
            failures += 1
            continue
        if not seal:
            print(f"ok  default_tenant {name} (AAD + fingerprint only)")
            continue
        print(f"ok  default_tenant {name}")
    return failures


def read_hex_key(text: str, *, lenient: bool = False) -> bytes | None:
    """hex_decode(text) for a row under one reading of what rule 1 leaves open, or None for a refusal.

    The strict reading refuses an uppercase digit, white space and a 0x prefix. The lenient one drops ASCII white
    space, then a leading 0x, and reads uppercase as lowercase. A row must get one verdict under both, so no row
    settles the question; this judges rows only.
    """
    if lenient:
        text = "".join(c for c in text if c not in ASCII_WHITE_SPACE)
        text = (text[2:] if text[:2] in ("0x", "0X") else text).lower()
    if len(text) % 2 or not set(text) <= LOWER_HEX:
        return None
    return bytes.fromhex(text)


def vector_tables(node: object, path: str = "") -> Iterator[str]:
    """The path of every list under a key ending in "vectors", at any depth, as tools/conformance.py finds them."""
    if isinstance(node, dict):
        for key, value in node.items():
            where = f"{path}.{key}" if path else key
            if key.endswith("vectors") and isinstance(value, list):
                yield where
            else:
                yield from vector_tables(value, where)


# Plausible wrong hex and raw-bytes entry points, one per mistake a master_key_input note names. Each returns the key
# bytes it would use, or None for a refusal (one that cannot parse its input refuses it), and must misjudge every row
# it lists; it lists a row only if that row's note names its mistake, so the notes and this table say the same thing.
# A decoding mistake sits behind a conformant length rule, so its row must catch the mistake itself, not a
# length check that happens to; where only one of the two rules lets the mistake through, the entry point uses that one.
HEX_DIGITS = frozenset(string.hexdigits)
# The row every other row comes from, which the notes call the accept row, and the one accept row whose key's first
# byte is 80 or above: one key cannot hold both a leading 00 byte and a first byte at 80 or above.
ACCEPT_ROW = "master_key_every_hex_digit"
FIRST_BYTE_80_ROW = "master_key_first_byte_80"
EXACTLY_32, AT_LEAST_32 = HEX_LENGTH_RULES[EXACTLY], HEX_LENGTH_RULES[OR_MORE]


def behind(accepts: Callable[[int], bool], key: bytes | None) -> bytes | None:
    """`key` if a length rule that `accepts` its length lets it through, else None."""
    return key if key is not None and accepts(len(key)) else None


def buffer_from_hex(text: str) -> bytes:
    """Node's Buffer.from(text, "hex"): byte pairs up to the first that is not hex; an odd last digit is dropped."""
    out = bytearray()
    for i in range(0, len(text) - 1, 2):
        if not set(text[i : i + 2]) <= HEX_DIGITS:
            break
        out.append(int(text[i : i + 2], 16))
    return bytes(out)


def big_integer(text: str) -> bytes:
    """int(text, 16) back to bytes at its minimal length: a leading 00 byte disappears."""
    value = int(text, 16)
    return value.to_bytes((value.bit_length() + 7) // 8, "big")


def twos_complement(text: str) -> bytes:
    """Java's new BigInteger(text, 16).toByteArray() (num-bigint's to_signed_bytes_be): the minimal bytes plus a 00
    sign byte when the top bit is set, which restores a leading 00 only when the byte after it is 80 or above."""
    value = int(text, 16)
    return value.to_bytes(value.bit_length() // 8 + 1, "big")


def padded_twos_complement(text: str) -> bytes | None:
    """int(text, 16).to_bytes(32, "big", signed=True) behind a strict hex check: right for a key whose first byte is
    below 80, refused for one at 80 or above, whose sign needs a 33rd byte (where Java's toByteArray() returns 33)."""
    if read_hex_key(text) is None:
        return None
    try:
        return int(text, 16).to_bytes(KEY_BYTES, "big", signed=True)
    except OverflowError:
        return None


def java_padded(text: str) -> bytes | None:
    """Java's new BigInteger(text, 16).toByteArray() left-padded to 32 bytes behind a strict 64-character hex check: a key
    whose first byte is below 80 comes back right, one whose first byte is 80 or above as 33 bytes (a 00 sign byte)."""
    if len(text) != 2 * KEY_BYTES or read_hex_key(text) is None:
        return None
    return twos_complement(text).rjust(KEY_BYTES, b"\0")


def digits_swapped(text: str) -> bytes | None:
    """Each byte read with its two digits swapped."""
    return None if len(text) % 2 else bytes.fromhex("".join(text[i + 1] + text[i] for i in range(0, len(text), 2)))


def digits_only_decoder(text: str) -> bytes:
    """Each digit's value taken as ord(c) - ord("0") in four bits: right for 0-9, wrong for every letter."""
    nibbles = [(ord(c) - ord("0")) & 0x0F for c in text]
    return bytes(hi << 4 | lo for hi, lo in zip(nibbles[::2], nibbles[1::2], strict=True))


def first_digit_decimal(text: str) -> bytes | None:
    """A decoder whose table for a byte's first digit holds only 0-9, so a letter there is refused."""
    return None if any(c not in string.digits for c in text[0::2]) else bytes.fromhex(text)


def signed_pairs(text: str) -> bytes | None:
    """Each pair parsed as a signed byte (Rust's i8::from_str_radix, Go's ParseInt(pair, 16, 8)): above 7f is refused."""
    key = bytes.fromhex(text)
    return None if any(b > 0x7F for b in key) else key


def through_text(key: bytes) -> bytes:
    """Key bytes passed through a text string at a str-typed boundary: each byte above 7f becomes two in UTF-8."""
    return key.decode("latin-1").encode("utf-8")


def sign_tolerant_pairs(text: str) -> bytes | None:
    """Pairs parsed one at a time by an integer parser that takes a sign, behind a 64-character check."""
    if len(text) != 2 * KEY_BYTES:
        return None
    try:
        return bytes(int(text[i : i + 2], 16) for i in range(0, len(text), 2))
    except ValueError:
        return None


def one_integer(text: str) -> bytes | None:
    """The string read as one integer (int(key, 16) takes a sign and a 0x prefix) back to 32 bytes, behind a 64-character check."""
    if len(text) != 2 * KEY_BYTES:
        return None
    try:
        return int(text, 16).to_bytes(KEY_BYTES, "big")
    except (ValueError, OverflowError):
        return None


def white_space_skipped(text: str) -> bytes | None:
    """A check for 64 characters or more, then Python's bytes.fromhex, which skips white space between pairs."""
    if len(text) < 2 * KEY_BYTES:
        return None
    try:
        return bytes.fromhex(text)
    except ValueError:
        return None


def prefix_stripped(text: str) -> bytes | None:
    """A 64-character check, then a 0x prefix stripped and the rest decoded with no check on the key's length."""
    if len(text) != 2 * KEY_BYTES:
        return None
    return read_hex_key(text[2:] if text[:2] in ("0x", "0X") else text)


def hex_decoded_first(raw: bytes) -> bytes:
    """A raw-bytes entry point that hex-decodes 64 ASCII hex digits before its length check."""
    text = raw.decode("latin-1")
    return bytes.fromhex(text) if len(text) == 2 * KEY_BYTES and set(text) <= HEX_DIGITS else raw


SHORT_ROWS = ("master_key_31_bytes", "master_key_24_bytes", "master_key_16_bytes")

